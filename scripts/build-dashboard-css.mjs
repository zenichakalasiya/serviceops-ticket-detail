/* One-off generator: the Dashboard prototype's tokens.css + global.css, SCOPED under `.dash-root`
 * so none of it reaches the rest of ServiceOps. Re-run only to re-import the source styles:
 *   node scripts/build-dashboard-css.mjs <path to ServiceOps_Dashboard_v2/src/styles>
 * Writes src/app/components/dashboard/dashboard.base.css. Hand edits go in dashboard.css, never here. */
import fs from 'fs';
import path from 'path';
import postcss from '../node_modules/.pnpm/postcss@8.5.15/node_modules/postcss/lib/postcss.js';

const dir = process.argv[2];
if (!dir) throw new Error('pass the source styles dir');
const ROOT = '.dash-root';
const scope = (sel) => {
  const s = sel.trim();
  if (s === ':root') return ROOT;
  if (/^(html|body|#app)\b/.test(s)) return null;               // the host app owns these
  if (s.startsWith('[data-theme="dark"]')) return ROOT + s;      // .dash-root[data-theme="dark"] …
  if (s === '*') return `${ROOT}, ${ROOT} *`;
  return `${ROOT} ${s}`;
};
const run = (css) => {
  const ast = postcss.parse(css);
  ast.walkAtRules('import', (r) => r.remove());
  ast.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const out = rule.selectors.map(scope).filter(Boolean);
    if (!out.length) rule.remove(); else rule.selectors = out;
  });
  return ast.toString();
};
const tokens = run(fs.readFileSync(path.join(dir, 'tokens.css'), 'utf8'));
const global = run(fs.readFileSync(path.join(dir, 'global.css'), 'utf8'));
fs.writeFileSync('src/app/components/dashboard/dashboard.base.css',
  `/* GENERATED by scripts/build-dashboard-css.mjs from ServiceOps_Dashboard_v2 — do not edit. */\n${tokens}\n${global}\n`);
console.log('ok');
