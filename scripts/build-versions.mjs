// Builds the module versions into dist/versions/ — run by CI after the main build.
//
// versions/versions.json lists every module's versions, each pinned to ONE commit. A commit is built
// ONCE: its output is kept on the `versions-builds` branch (builds/<sha>/), so later deploys only copy
// it. That keeps main light and makes an old version truly frozen — it is the old code, not today's
// code pretending.
//
// Output:
//   dist/versions/index.html              — every module, every version, its major changes
//   dist/versions/builds/<sha>/           — one full build per pinned commit (shared by every
//                                            module version pinned to that commit)
//   dist/versions/<module>/<version>/     — a short permanent link that lands on the module's screen
//
// Usage: node scripts/build-versions.mjs            (CI: builds missing commits, pushes the branch)
//        node scripts/build-versions.mjs --page-only (local: just writes the index page, no builds)

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const BASE = '/serviceops-ticket-detail/versions/';
const DIST = path.join(ROOT, 'dist', 'versions');
const VB = path.join(ROOT, '.vb');            // worktree of the versions-builds branch
const BRANCH = 'versions-builds';
const pageOnly = process.argv.includes('--page-only');

const sh = (cmd, opts = {}) => execSync(cmd, { stdio: 'inherit', ...opts });
const out = (cmd, opts = {}) => execSync(cmd, { encoding: 'utf8', ...opts }).trim();

const registry = JSON.parse(fs.readFileSync(path.join(ROOT, 'versions', 'versions.json'), 'utf8'));

// Resolve every pinned commit to a stable 12-character id (a short sha in the registry may grow
// ambiguous as history grows; the folder name must never change).
const shaOf = new Map();
for (const m of registry.modules) for (const v of m.versions) {
  if (!shaOf.has(v.commit)) {
    const full = pageOnly ? v.commit : out(`git rev-parse ${v.commit}^{commit}`);
    shaOf.set(v.commit, full.slice(0, 12));
  }
}
const shas = [...new Set(shaOf.values())];

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });

if (!pageOnly) {
  // ── the versions-builds branch, as a worktree ──
  fs.rmSync(VB, { recursive: true, force: true });
  try { sh(`git worktree prune`); } catch {}
  const exists = out(`git ls-remote --heads origin ${BRANCH}`) !== '';
  if (exists) {
    sh(`git fetch --no-tags origin ${BRANCH}`);
    sh(`git worktree add --detach "${VB}" FETCH_HEAD`);
  } else {
    sh(`git worktree add --detach "${VB}"`);
    sh(`git checkout --orphan ${BRANCH}`, { cwd: VB });
    sh(`git rm -rfq .`, { cwd: VB });
    fs.writeFileSync(path.join(VB, 'README.md'), '# Built module versions\n\nGenerated by scripts/build-versions.mjs on main. Do not edit by hand.\n');
  }

  // ── build each commit that has no build yet ──
  let built = 0;
  for (const sha of shas) {
    const target = path.join(VB, 'builds', sha);
    if (fs.existsSync(path.join(target, 'index.html'))) { console.log(`✓ ${sha} already built`); continue; }
    console.log(`▶ building ${sha}`);
    const src = path.join(ROOT, '..', `vsrc-${sha}`);
    fs.rmSync(src, { recursive: true, force: true });
    sh(`git worktree add --detach "${src}" ${sha}`);
    sh(`pnpm install --no-frozen-lockfile`, { cwd: src });
    sh(`pnpm exec vite build --base=${BASE}builds/${sha}/ --outDir "${target}" --emptyOutDir`, { cwd: src });
    sh(`git worktree remove --force "${src}"`);
    built++;
  }

  if (built) {
    sh(`git add -A`, { cwd: VB });
    sh(`git -c user.name="github-actions[bot]" -c user.email="41898282+github-actions[bot]@users.noreply.github.com" commit -qm "Build ${built} module version(s)"`, { cwd: VB });
    sh(`git push origin HEAD:refs/heads/${BRANCH}`, { cwd: VB });
  }

  // ── copy only the builds still referenced (an updated version drops its old build from the site;
  //    it stays on the branch) ──
  for (const sha of shas) fs.cpSync(path.join(VB, 'builds', sha), path.join(DIST, 'builds', sha), { recursive: true });
}

// ── short links: /versions/<module>/<version>/ → that build, on that module's screen ──
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
for (const m of registry.modules) for (const v of m.versions) {
  const dir = path.join(DIST, m.id, v.version);
  fs.mkdirSync(dir, { recursive: true });
  const to = `../../builds/${shaOf.get(v.commit)}/${m.route}`;
  fs.writeFileSync(path.join(dir, 'index.html'),
    `<!doctype html><meta charset="utf-8"><title>${esc(m.name)} ${esc(v.version)}</title>` +
    `<meta http-equiv="refresh" content="0; url=${esc(to)}"><script>location.replace(${JSON.stringify(to)})</script>` +
    `<a href="${esc(to)}">Open ${esc(m.name)} ${esc(v.version)}</a>`);
}

// ── the index page ──
const fmt = (d) => new Date(d + 'T00:00:00').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
const areas = [...new Set(registry.modules.map((m) => m.area))];
const card = (m) => {
  const vs = [...m.versions].reverse(); // newest first
  return `<section class="mod" id="${esc(m.id)}">
  <header><h3>${esc(m.name)}</h3><a class="open" href="${esc(m.id)}/${esc(vs[0].version)}/">Open ${esc(vs[0].version)} ↗</a></header>
  <ol>${vs.map((v, i) => `
    <li${i === 0 ? ' class="latest"' : ''}>
      <div class="vh"><a class="tag" href="${esc(m.id)}/${esc(v.version)}/">${esc(v.version)}</a>
        <span class="meta">${esc(fmt(v.date))} · <code>${esc(v.commit)}</code></span>${i === 0 ? '<span class="cur">Latest</span>' : ''}</div>
      <ul>${v.changes.map((c) => `<li>${esc(c)}</li>`).join('')}</ul>
    </li>`).join('')}
  </ol>
</section>`;
};
const total = registry.modules.reduce((n, m) => n + m.versions.length, 0);
fs.writeFileSync(path.join(DIST, 'index.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Module Versions · Motadata ServiceOps</title>
<link rel="preconnect" href="https://fonts.googleapis.com"><link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
<style>
  *{box-sizing:border-box} body{margin:0;background:#F7F9FC;color:#364658;font:13px/1.55 Inter,system-ui,sans-serif}
  .wrap{max-width:1120px;margin:0 auto;padding:32px 16px 64px}
  h1{margin:0;font-size:20px;font-weight:600;color:#1D2A3E} .sub{margin:4px 0 28px;color:#64748B}
  h2{margin:28px 0 10px;font-size:11px;font-weight:600;letter-spacing:.06em;text-transform:uppercase;color:#7B8FA5}
  .grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(340px,1fr));gap:12px}
  .mod{background:#fff;border:1px solid #E5E7EB;border-radius:8px;padding:14px 16px}
  .mod header{display:flex;align-items:center;justify-content:space-between;gap:12px;margin-bottom:10px}
  h3{margin:0;font-size:14px;font-weight:600;color:#1D2A3E}
  a{color:#3D8BD0;text-decoration:none} a:hover{text-decoration:underline}
  .open{font-size:12px;font-weight:500;white-space:nowrap}
  ol{list-style:none;margin:0;padding:0} ol>li{padding:8px 0;border-top:1px solid #F1F5F9} ol>li:first-child{border-top:0;padding-top:0}
  .vh{display:flex;align-items:center;gap:8px;flex-wrap:wrap}
  .tag{display:inline-block;border-radius:4px;background:#e8f4fd;padding:1px 7px;font-weight:600;font-size:12px}
  .meta{color:#7B8FA5;font-size:12px} code{font:11px ui-monospace,monospace}
  .cur{border-radius:2px;background:#ECFDF3;color:#22A06B;padding:0 6px;font-size:11px;font-weight:600}
  ul{margin:6px 0 0;padding-left:18px} ul li{margin:2px 0}
</style></head><body><div class="wrap">
<h1>Module versions</h1>
<p class="sub">${registry.modules.length} modules · ${total} versions. Each version is the app exactly as it was on that commit — open two versions side by side to compare.</p>
${areas.map((a) => `<h2>${esc(a)}</h2><div class="grid">${registry.modules.filter((m) => m.area === a).map(card).join('\n')}</div>`).join('\n')}
</div></body></html>
`);
console.log(`✓ versions page: ${registry.modules.length} modules, ${total} versions, ${shas.length} build(s)`);
